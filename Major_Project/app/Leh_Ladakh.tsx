import { FontAwesome6 } from '@expo/vector-icons';
import Animated, { interpolate, useAnimatedRef, useAnimatedStyle, useScrollViewOffset } from 'react-native-reanimated';

const { width, height } = Dimensions.get("window");
const imgHeight = height * 0.4;

const Leh_Ladakh = () => {

  const [showFullText, setShowFullText] = useState(false);
    const scrollRef = useAnimatedRef<Animated.ScrollView>();
    const scrollOffset = useScrollViewOffset(scrollRef);
    const imageAnimatedStyle = useAnimatedStyle(() => {
        return {
            transform: [{translateY: interpolate(scrollOffset.value, [-imgHeight, 0, imgHeight], [-imgHeight /2, 0, imgHeight * 0.75] )},
            {
                scale: interpolate(
                    scrollOffset.value,[-imgHeight, 0, imgHeight], [2, 1, 1]
                )
            }
        ]
        }
    });
    const openGoogleMaps = () => {
      const googleMapsUrl = `https://www.google.com/maps/search/?api=1&query=34.152586,77.577053`;
      Linking.openURL(googleMapsUrl).catch(err => console.error("An error occurred", err));
    };
    const fullHistoryText = `History :Leh-Ladakh, an enchanting region in northern India, has a rich history intertwined with trade, culture, and spirituality. Situated on the ancient Silk Route, it facilitated trade between Central Asia and the Indian subcontinent. The Namgyal dynasty, established in the 15th century, significantly shaped Leh's political and cultural landscape. Influenced by Buddhism, Ladakh is home to stunning monasteries like Hemis, Alchi, and Thiksey, showcasing Tibetan art and heritage. The region witnessed Dogra rule in the 19th century and became part of independent India in 1947. Declared a Union Territory in 2019, Ladakh is renowned for its dramatic landscapes, adventure sports, and spiritual aura`;
  
    const truncatedHistoryText = `${fullHistoryText.substring(0, 150)}...`;
    const time = new Date();
    const hour = time.getHours();
  return (
    <>
        <Stack.Screen options={{ 
            headerTransparent: true,
            headerTitle: "",
            headerLeft: () => {
                return (  // Add return here
                <TouchableOpacity 
                  onPress={() => router.back()} 
                  style={{ backgroundColor: "rgba(255, 255, 255, 0.5)", borderRadius: 10, padding: 4, marginLeft: width * 0.05 }}
                >
                  <View style={styles.nav_icon}>
                    <FontAwesome6 name='arrow-left-long' size={20} />
                  </View>
                </TouchableOpacity>
              );
            }
        }}/>
        <Animated.ScrollView ref={scrollRef} showsVerticalScrollIndicator={false}>
            <Animated.Image source={require('@/assets/images/Leh_Ladakh.png')} style={[styles.photo, imageAnimatedStyle]}/>
            <View style={styles.history}>
              <Text style={styles.text}>
                {showFullText ? fullHistoryText : truncatedHistoryText}
              </Text>

              <TouchableOpacity onPress={() => setShowFullText(!showFullText)}>
                <Text style={styles.readMoreText}>
                  {showFullText ? "Show Less" : "Read More"}
                </Text>
              </TouchableOpacity>
            </View>
            <View style={styles.timing}>
                <Text style={styles.text}>Timing : 7 AM to 7 PM</Text>
                { 7 <= hour && 18 >= hour ? 
                <Text style={styles.time}>Open</Text> :
                <Text style={styles.time1}>Close</Text>
                }
            </View>
            <View style={styles.ticket}>
                <Text style={styles.text}>Ticket :No entry fee.
               </Text>
                <TouchableOpacity activeOpacity={0.7} style = {styles.book}>
                    <Text style={styles.text}>Book</Text>
                </TouchableOpacity>
            </View>
            <View style={styles.address}>
                <Text style={styles.text_address}>Address :Leh-Ladakh, Union Territory of Ladakh, India
                Pin Code: 194101</Text>
                <View style={styles.buttonWrapper}>
                <TouchableOpacity activeOpacity={0.7} style={styles.btn} onPress={openGoogleMaps}>
                      <Text style={styles.text}>Show on map</Text>
                  </TouchableOpacity>
                </View>
            </View>
        </Animated.ScrollView>
    </>
  )
}

